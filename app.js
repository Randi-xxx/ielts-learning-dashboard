function progressForDay(key) {
  const day = days[key];
  const done = Object.values((state[key] || {}).tasks || {}).filter(Boolean).length;
  return day.tasks.length ? Math.round((done / day.tasks.length) * 100) : 0;
}

function renderCalendar() {
  const year = calendarDate.getFullYear();
  const month = calendarDate.getMonth();
  document.getElementById("calendar-month").textContent = `${year} 年 ${month + 1} 月`;
  const firstWeekday = new Date(year, month, 1).getDay();
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  const lookup = Object.entries(days).reduce((all, [key, day]) => ({ ...all, [day.date]: key }), {});
  const cells = Array.from({ length: firstWeekday + daysInMonth }, (_, index) => {
    if (index < firstWeekday) return "<span></span>";
    const dateNumber = index - firstWeekday + 1;
    const dateValue = `${year}-${String(month + 1).padStart(2, "0")}-${String(dateNumber).padStart(2, "0")}`;
    const key = lookup[dateValue];
    if (!key) return `<span class="calendar-day empty">${dateNumber}</span>`;
    const progress = progressForDay(key);
    const status = progress === 100 ? "complete" : progress > 0 ? "partial" : "empty";
    const selected = key === currentDay ? "is-selected" : "";
    return `<button type="button" class="calendar-day is-available ${status} ${selected}" data-day="${key}" aria-label="${days[key].label}，完成率 ${progress}%">${dateNumber}</button>`;
  });
  document.getElementById("calendar-grid").innerHTML = cells.join("");
  document.querySelectorAll(".calendar-day.is-available").forEach(button => button.addEventListener("click", () => {
    currentDay = button.dataset.day;
    state.currentDay = currentDay;
    saveState();
    renderDay();
  }));
}

function renderTasks(day) {
  const stored = dayState().tasks || {};
  taskList.innerHTML = day.tasks.map(([title, description, time], index) => {
    const id = `${currentDay}-task-${index}`;
    const checked = stored[index] ? "checked" : "";
    return `<label class="task-item ${stored[index] ? "is-done" : ""}" for="${id}"><input id="${id}" type="checkbox" data-task="${index}" ${checked}><span><h3>${title}</h3><p>${description}</p></span><span class="task-time">${time}</span></label>`;
  }).join("");
  taskList.querySelectorAll("input[data-task]").forEach(input => input.addEventListener("change", event => {
    const current = dayState();
    current.tasks = current.tasks || {};
    current.tasks[event.target.dataset.task] = event.target.checked;
    state[currentDay] = current;
    saveState();
    renderDay();
  }));
}

function updateProgress(day) {
  const completed = Object.values(dayState().tasks || {}).filter(Boolean).length;
  const total = day.tasks.length;
  const value = total ? Math.round((completed / total) * 100) : 0;
  progressNumber.textContent = value;
  progressBar.style.width = `${value}%`;
  progressBar.parentElement.setAttribute("aria-valuenow", value);
  progressCaption.textContent = `完成 ${completed} / ${total} 项`;
}

